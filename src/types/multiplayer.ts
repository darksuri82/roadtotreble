import type {
  FormationId,
  ManagerAvatarConfig,
  ManagerTraitId,
  UserClubProfile,
} from './game';
import type {
  LeagueId,
  LiveHalftimeState,
  MatchResult,
  TacticId,
} from './league';
import type { Player } from './player';

/** Extensible multiplayer room modes (Phase 2 multi-league ready) */
export type MpRoomMode = '1v1' | '1v1_blind' | '1v1_blind_draft' | 'multi_league';

export type MpRoomStatus =
  | 'lobby'
  | 'drafting'
  | 'tactics'
  | 'pre_match'
  | 'live_match'
  | 'live'
  | 'playing'
  | 'match'
  | 'in_match'
  | 'in_progress'
  | 'first_half'
  | 'simulating'
  | 'finished'
  | 'completed'
  | 'ended';

export function isMpTacticsStatus(status: string | undefined | null): boolean {
  return status === 'tactics' || status === 'pre_match';
}

export function isMpLiveMatchStatus(status: string | undefined | null): boolean {
  return (
    status === 'live_match' ||
    status === 'live' ||
    status === 'playing' ||
    status === 'match' ||
    status === 'in_match' ||
    status === 'in_progress' ||
    status === 'first_half' ||
    status === 'simulating'
  );
}

export function isMpFinishedStatus(status: string | undefined | null): boolean {
  return status === 'finished' || status === 'completed' || status === 'ended';
}

export interface MpRoomSettings {
  draftLeaguePool: LeagueId[];
  knockoutRules: boolean;
  /** Incremented whenever a new draft rematch starts so clients reset local draft caches */
  draftGeneration?: number;
  /** Incremented on every match start / same-team rematch */
  matchNumber?: number;
}

/**
 * Complete private squad payload uploaded ONLY after draft finishes.
 * During status === 'drafting', this remains null in DB so opponent cannot inspect picks.
 */
export interface MpLineupPayload {
  managerTraitId: ManagerTraitId;
  formation: FormationId;
  defaultTactic: TacticId;
  starters: Player[];
  bench: Player[];
  submittedAt: string;
}

export type MpTacticBarrierPhase =
  | 'pre_match'
  | 'halftime'
  | 'extra_time_break'
  | 'extra_time_ht';

export interface MpTacticSubmission {
  phase: MpTacticBarrierPhase;
  /** Nonce ties submission to the specific match/barrier instance */
  barrierKey: string;
  formation: FormationId;
  tactic: TacticId;
  starters: Player[];
  bench: Player[];
  subPlayerIds: string[];
  extraTimeSubIds?: string[];
  submittedAt: string;
}

export type MpMatchPhase =
  | 'first_half'
  | 'halftime'
  | 'second_half'
  | 'extra_time_break'
  | 'extra_time'
  | 'extra_time_ht'
  | 'extra_time_2'
  | 'penalties'
  | 'finished';

/**
 * Authoritative match state calculated by Host and synced to both clients via mp_rooms.match_state.
 * Host is always homeTeamId ('mp-host'), Guest is always awayTeamId ('mp-guest').
 */
export interface MpMatchState {
  matchId: string;
  matchNumber: number;
  phase: MpMatchPhase;
  /** Host (home) & Guest (away) latest snapshot for scoreboard & broadcast */
  hostTeamId: string;
  guestTeamId: string;
  hostFormation: FormationId;
  guestFormation: FormationId;
  hostTactic: TacticId;
  guestTactic: TacticId;
  hostManagerTraitId: ManagerTraitId;
  guestManagerTraitId: ManagerTraitId;
  hostStarters: Player[];
  hostBench: Player[];
  guestStarters: Player[];
  guestBench: Player[];
  hostFirstHalfStarters: Player[];
  guestFirstHalfStarters: Player[];
  hostHalftimeSubIds: string[];
  guestHalftimeSubIds: string[];
  hostEtSubIds: string[];
  guestEtSubIds: string[];
  /** Shared 1st-half / live broadcast timeline generated by Host */
  liveHalftime: LiveHalftimeState;
  /** Final match result once 2nd half (or ET/PK) completes */
  finalResult?: MatchResult | null;
  /** Synced rematch series tally */
  seriesWins?: {
    host: number;
    guest: number;
    draws: number;
  };
  updatedAt: string;
}

export interface MpRoomRow {
  id: string;
  code: string;
  mode: MpRoomMode;
  status: MpRoomStatus;
  host_player_id: string;
  settings: MpRoomSettings;
  match_state: MpMatchState | null;
  created_at: string;
  updated_at: string;
}

export interface MpRoomPlayerRow {
  id: string;
  room_id: string;
  player_id: string;
  seat: number;
  nickname: string;
  avatar_json: ManagerAvatarConfig;
  club_profile: UserClubProfile;
  is_ready: boolean;
  draft_progress: number;
  draft_completed: boolean;
  lineup_payload: MpLineupPayload | null;
  tactic_submission: MpTacticSubmission | null;
  updated_at: string;
}

export interface MpRoomSnapshot {
  room: MpRoomRow;
  players: MpRoomPlayerRow[];
}

export interface LocalBlindDraftCache {
  roomCode: string;
  playerId: string;
  draftGeneration: number;
  stage: 'manager' | 'draft';
  managerTraitId: ManagerTraitId | null;
  rerollsRemaining: number;
  hasSpunManager: boolean;
  formation: FormationId;
  defaultTactic: TacticId;
  starters: (Player | null)[];
  bench: (Player | null)[];
  completed: boolean;
}
